export function studentKey(classId, name) {
  return `${classId}::${name}`
}

export function isValidStudent(classId, name) {
  const list = ROSTER[classId]
  return Array.isArray(list) && list.includes(name)
}

export function classSize(classId) {
  const list = ROSTER[classId]
  return Array.isArray(list) ? list.length : 0
}

export const TOTAL_STUDENTS = CLASS_IDS.reduce((sum, id) => sum + classSize(id), 0)
