export const QUIZ_TOTAL = QUIZ_QUESTIONS.length
export const QUIZ_MAX_SCORE = 100

/** 去掉答案，用于下发给学生端 */
export function publicQuestions() {
  return QUIZ_QUESTIONS.map(({ id, tag, stem, options }) => ({ id, tag, stem, options }))
}

/** 判分：answers 为 { [questionId]: optionIndex } */
export function gradeQuiz(answers) {
  const detail = QUIZ_QUESTIONS.map((q) => {
    const picked = answers && typeof answers[q.id] === 'number' ? answers[q.id] : -1
    return { id: q.id, picked, correct: q.answer, ok: picked === q.answer }
  })
  const correct = detail.filter((d) => d.ok).length
  return {
    correct,
    total: QUIZ_TOTAL,
    score: Math.round((correct / QUIZ_TOTAL) * QUIZ_MAX_SCORE),
    detail,
  }
}
